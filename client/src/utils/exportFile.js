import { jsPDF } from "jspdf"
import autoTable from "jspdf-autotable"

// rows = array of arrays. Numbers stay numbers. Text starting with = + - @ is neutralised
// so a hostile customer name can never run as a spreadsheet formula.
export const downloadCsv = (filename, rows) => {
    const cell = (value) => {
        if (typeof value === "number") return String(value)
        let text = String(value ?? "")
        if (/^[=+\-@\t\r]/.test(text)) text = "'" + text
        return `"${text.replace(/"/g, '""')}"`
    }
    const csv = "\ufeff" + rows.map((row) => row.map(cell).join(",")).join("\r\n")
    const url = URL.createObjectURL(new Blob([csv], { type: "text/csv;charset=utf-8" }))
    const link = document.createElement("a")
    link.href = url
    link.download = filename
    link.click()
    URL.revokeObjectURL(url)
}

export const downloadPdf = ({ filename, title, lines = [], head, body }) => {
    const doc = new jsPDF({ orientation: head.length > 6 ? "landscape" : "portrait" })

    doc.setFontSize(16)
    doc.text(title, 14, 16)
    doc.setFontSize(10)
    let y = 23
    lines.forEach((line) => {
        doc.text(line, 14, y)
        y += 5
    })

    autoTable(doc, {
        startY: y + 2,
        head: [head],
        body,
        styles: { fontSize: 9 },
        headStyles: { fillColor: [0, 0, 0] },
    })

    const pages = doc.getNumberOfPages()
    const width = doc.internal.pageSize.getWidth()
    const height = doc.internal.pageSize.getHeight()
    for (let i = 1; i <= pages; i++) {
        doc.setPage(i)
        doc.setFontSize(8)
        doc.text(`Generated by Your Khaata on ${new Date().toLocaleDateString("en-IN")}`, 14, height - 8)
        doc.text(`Page ${i} of ${pages}`, width - 14, height - 8, { align: "right" })
    }

    doc.save(filename)
}

export const downloadReceiptPdf = ({ filename, lines }) => {
    const doc = new jsPDF()
    doc.setFontSize(18)
    doc.text("Payment Receipt", 14, 20)
    doc.setFontSize(11)
    let y = 32
    lines.forEach((line) => {
        doc.text(line, 14, y)
        y += 8
    })
    doc.setFontSize(8)
    doc.text("Manually recorded by the business. Generated by Your Khaata.", 14, y + 8)
    doc.save(filename)
}

// A simple document (used for invoices): header lines, a table, totals, footer notes
export const downloadDocumentPdf = ({ filename, title, leftLines, rightLines, head, body, totals, footerLines = [] }) => {
    const doc = new jsPDF()
    const width = doc.internal.pageSize.getWidth()

    doc.setFontSize(18)
    doc.text(title, 14, 18)
    doc.setFontSize(10)
    leftLines.forEach((line, i) => doc.text(line, 14, 28 + i * 5))
    rightLines.forEach((line, i) => doc.text(line, width - 14, 28 + i * 5, { align: "right" }))

    const startY = 28 + Math.max(leftLines.length, rightLines.length) * 5 + 4
    autoTable(doc, {
        startY,
        head: [head],
        body,
        styles: { fontSize: 9 },
        headStyles: { fillColor: [0, 0, 0] },
    })

    let y = doc.lastAutoTable.finalY + 8
    totals.forEach(([label, value]) => {
        if (y > 275) {
            doc.addPage()
            y = 20
        }
        doc.text(label, width - 75, y)
        doc.text(value, width - 14, y, { align: "right" })
        y += 6
    })

    y += 4
    footerLines.forEach((line) => {
        if (y > 280) {
            doc.addPage()
            y = 20
        }
        doc.text(line, 14, y)
        y += 5
    })

    doc.save(filename)
}